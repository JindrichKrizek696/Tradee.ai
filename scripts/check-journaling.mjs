// Kontrola přehledu Journalingu: node --experimental-strip-types scripts/check-journaling.mjs
import {overview,trend} from '../lib/discipline/overview.ts';
const fails=[];
const check=(name,ok,got)=>{console.log((ok?'ok   ':'FAIL ')+name+(ok?'':' → '+JSON.stringify(got)));if(!ok)fails.push(name)};
const T=(id,source,pnl)=>({id,source,pnl});
const trades=[T('mt:1','mt',10),T('mt:2','mt',-5),T('mt:3','mt',20),T('man:4','manual',7),T('man:5','manual',-3)];
const strategies=[{id:'s1',name:'Breakout'},{id:'s2',name:'Pullback'}];
const reviews={'man:4':{rating:4,strategyId:'s1',emotions:[]},'mt:1':{rating:5,strategyId:'s1',emotions:['calm']},'mt:2':{rating:null,strategyId:'s2',emotions:[]}};
const viol={'mt:2':[{rule:'sl_required',needsReason:false,reasoned:false},{rule:'no_early_close',needsReason:true,reasoned:false}],'mt:3':[{rule:'no_early_close',needsReason:true,reasoned:true}]};
let o=overview(trades,reviews,{'mt:2':[{rule:'sl_required',needsReason:false,reasoned:false}]},{},strategies);
check('judged 4, clean 3, discipline 75',o.judged===4&&o.clean===3&&o.discipline===75,o);
check('ruční bez review se nepočítá',o.judged===4);
check('top sl_required',o.top?.rule==='sl_required'&&o.top.count===1,o.top);
check('toReview = bez ratingu (mt:2,mt:3,man:5)',o.toReview===3,o.toReview);
check('avgRating 4,5',o.avgRating===4.5,o.avgRating);
o=overview(trades,reviews,{'mt:2':[{rule:'sl_required',needsReason:false,reasoned:false}]},{'man:4':['c1'],'mt:1':['c1']},strategies);
check('vlastní pravidlo → není čistý',o.clean===1&&o.discipline===25,o);
check('top custom:c1 (2×)',o.top?.rule==='custom:c1'&&o.top.count===2,o.top);
o=overview(trades,reviews,viol,{},strategies);
check('needReason jen nezdůvodněné',o.needReason===1,o.needReason);
check('top remíza → abecedně',o.top?.rule==='no_early_close'&&o.top.count===2,o.top);
o=overview(trades,reviews,{},{'man:4':['b'],'mt:1':['a']},strategies);
check('top remíza custom abecedně',o.top?.rule==='custom:a',o.top);
o=overview(trades,reviews,{},{},strategies);
check('byStrategy pořadí a Bez strategie poslední',JSON.stringify(o.byStrategy.map(s=>[s.id,s.trades]))===JSON.stringify([['s1',2],['s2',1],[null,2]]),o.byStrategy);
const b=o.byStrategy;
check('byStrategy winRate/pnl/avgRating',b[0].winRate===100&&b[0].pnl===17&&b[0].avgRating===4.5&&b[1].winRate===0&&b[1].avgRating===null&&b[2].winRate===50&&b[2].name==='Bez strategie',b);
// označené jako „neplatí“ se nepočítají (disciplína, top, needReason)
o=overview(trades,reviews,{'mt:2':[{rule:'sl_required',needsReason:false,reasoned:false,dismissed:true}]},{},strategies);
check('dismissed → čistý obchod, discipline 100, bez top',o.clean===4&&o.discipline===100&&o.top===null,o);
o=overview(trades,reviews,{'mt:2':[{rule:'sl_required',needsReason:false,reasoned:false},{rule:'no_early_close',needsReason:true,reasoned:false,dismissed:true}]},{},strategies);
check('dismissed se nepočítá do needReason ani top',o.needReason===0&&o.top?.rule==='sl_required'&&o.clean===3,o);
o=overview([T('man:9','manual',1)],{},{},{},[]);
check('judged 0 → discipline null',o.discipline===null&&o.judged===0&&o.top===null&&o.avgRating===null&&o.toReview===1,o);
o=overview([T('mt:1','mt',1)],{'mt:1':{rating:null,strategyId:'zmizela',emotions:[]}},{},{},strategies);
check('neznámá strategie → Bez strategie',o.byStrategy.length===1&&o.byStrategy[0].id===null,o.byStrategy);
check('trend(80,75)=5',trend(80,75)===5);
check('trend(null,5)=null',trend(null,5)===null&&trend(5,null)===null);
if(fails.length){console.log('\n'+fails.length+' selhalo');process.exit(1)}console.log('\nvše ok');
