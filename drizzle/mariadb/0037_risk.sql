CREATE TABLE IF NOT EXISTS account_profiles(
  id VARCHAR(40) NOT NULL PRIMARY KEY,
  user_id VARCHAR(128) NOT NULL,
  name VARCHAR(60) NOT NULL,
  kind VARCHAR(10) NOT NULL DEFAULT 'personal',
  currency VARCHAR(3) NOT NULL,
  start_balance DOUBLE NOT NULL,
  start_date DATE NOT NULL,
  balance DOUBLE NULL,
  link_id VARCHAR(40) NULL,
  fee_challenge DOUBLE NULL,
  fee_activation DOUBLE NULL,
  archived TINYINT(1) NOT NULL DEFAULT 0,
  created DATETIME NOT NULL,
  updated DATETIME NOT NULL,
  INDEX account_profiles_user(user_id),
  UNIQUE KEY account_profiles_link(user_id,link_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
