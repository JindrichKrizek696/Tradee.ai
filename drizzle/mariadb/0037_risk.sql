CREATE TABLE IF NOT EXISTS instruments(
  id VARCHAR(32) NOT NULL PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  kind VARCHAR(8) NOT NULL,
  venue VARCHAR(40) NOT NULL DEFAULT '',
  quote_ccy VARCHAR(3) NOT NULL,
  tick_size DOUBLE NOT NULL,
  tick_value DOUBLE NOT NULL,
  contract_size DOUBLE NOT NULL,
  lot_step DOUBLE NOT NULL,
  min_lot DOUBLE NOT NULL,
  pip DOUBLE NULL,
  unit VARCHAR(10) NOT NULL,
  sessions VARCHAR(20) NOT NULL DEFAULT '',
  data_symbol VARCHAR(32) NULL,
  market_id VARCHAR(32) NULL,
  proxy TINYINT(1) NOT NULL DEFAULT 0,
  has_volume TINYINT(1) NOT NULL DEFAULT 0,
  has_cot TINYINT(1) NOT NULL DEFAULT 0,
  has_fundamentals TINYINT(1) NOT NULL DEFAULT 0,
  aliases VARCHAR(255) NOT NULL DEFAULT '',
  INDEX instruments_market(market_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
